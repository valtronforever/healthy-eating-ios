#!/usr/bin/env python3
"""Generate the app's design tokens from design/system/tokens.json.

Writes, relative to the repository root:

- Shared/DesignTokens.xcassets/<token>.colorset
  (one color set per color token, Any and Dark appearances; `Shared/` is compiled into the app
  and the widget extension)
- HealthyEating/Resources/Assets.xcassets/AccentColor.colorset
  (the app's global accent color, a copy of the `accent` token)
- Shared/DesignTokens.generated.swift
  (Color and ShapeStyle extensions, Spacing and Radius enums)

Usage (standard library only):

    python3 design/tools/generate_design_tokens.py          # write files
    python3 design/tools/generate_design_tokens.py --check  # exit 1 if out of date

Never edit the generated files by hand: change tokens.json and run this script.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "design" / "system" / "tokens.json"
ASSETS = ROOT / "HealthyEating" / "Resources" / "Assets.xcassets"
COLORS_DIR = ROOT / "Shared" / "DesignTokens.xcassets"
ACCENT_DIR = ASSETS / "AccentColor.colorset"
SWIFT_OUT = ROOT / "Shared" / "DesignTokens.generated.swift"

# Names that already exist on `ShapeStyle` in SwiftUI (for example `LinkShapeStyle.link`).
# They get a `Color` static only, so `.foregroundStyle(.link)` stays unambiguous.
SHAPE_STYLE_EXCLUDED = {"link"}

XCODE_INFO = {"author": "xcode", "version": 1}


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def hex_components(value: str) -> dict[str, str]:
    match = re.fullmatch(r"#([0-9a-fA-F]{6})", value)
    if not match:
        raise ValueError(f"unsupported color value {value!r}; expected #rrggbb")
    digits = match.group(1).upper()
    return {
        "alpha": "1.000",
        "red": f"0x{digits[0:2]}",
        "green": f"0x{digits[2:4]}",
        "blue": f"0x{digits[4:6]}",
    }


def resolve_colors(tokens: list[dict]) -> list[tuple[str, dict[str, str], str]]:
    by_name = {t["name"]: t for t in tokens}
    resolved = []
    for token in tokens:
        value = token["value"]
        seen = {token["name"]}
        while isinstance(value, str):
            alias = re.fullmatch(r"\{([a-z0-9-]+)\}", value)
            if not alias or alias.group(1) not in by_name or alias.group(1) in seen:
                raise ValueError(f"cannot resolve color token {token['name']!r}: {value!r}")
            seen.add(alias.group(1))
            value = by_name[alias.group(1)]["value"]
        resolved.append((token["name"], {"light": value["light"], "dark": value["dark"]}, token.get("usage", "")))
    return resolved


def colorset(light: str, dark: str) -> str:
    content = {
        "colors": [
            {"color": {"color-space": "srgb", "components": hex_components(light)}, "idiom": "universal"},
            {
                "appearances": [{"appearance": "luminosity", "value": "dark"}],
                "color": {"color-space": "srgb", "components": hex_components(dark)},
                "idiom": "universal",
            },
        ],
        "info": XCODE_INFO,
    }
    return json.dumps(content, indent=2) + "\n"


def px(value: str) -> str:
    match = re.fullmatch(r"(\d+(?:\.\d+)?)px", value)
    if not match:
        raise ValueError(f"unsupported length {value!r}; expected <n>px")
    return match.group(1)


def swift_source(colors, spacing, radius) -> str:
    out = [
        "// Generated by design/tools/generate_design_tokens.py from design/system/tokens.json.",
        "// Do not edit by hand: change tokens.json and run the script again.",
        "",
        "import SwiftUI",
        "",
        "/// Color tokens. Each one is an Asset Catalog color set with Any and Dark appearances.",
        "extension Color {",
    ]
    for name, _, usage in colors:
        out.append(f"    /// `{name}`: {usage}")
        out.append(f'    nonisolated static let {camel(name)} = Color("{name}", bundle: .main)')
    out += [
        "}",
        "",
        "/// Lets token colors be used where a `ShapeStyle` is expected, for example `.foregroundStyle(.inkMuted)`.",
        "extension ShapeStyle where Self == Color {",
    ]
    for name, _, _ in colors:
        if name in SHAPE_STYLE_EXCLUDED:
            continue
        out.append(f"    nonisolated static var {camel(name)}: Color {{ Color.{camel(name)} }}")
    out += [
        "}",
        "",
        "/// Spacing tokens in points (4 pt base).",
        "nonisolated enum Spacing {",
    ]
    for token in spacing:
        name = token["name"]
        swift_name = "tapTarget" if name == "tap-target" else "s" + name.removeprefix("space-")
        out.append(f"    /// `{name}`: {token.get('usage', '')}")
        out.append(f"    static let {swift_name}: CGFloat = {px(token['value'])}")
    out += [
        "}",
        "",
        "/// Corner radius tokens in points. Always use them with `style: .continuous`.",
        "nonisolated enum Radius {",
    ]
    for token in radius:
        name = token["name"]
        out.append(f"    /// `{name}`: {token.get('usage', '')}")
        out.append(f"    static let {camel(name.removeprefix('radius-'))}: CGFloat = {px(token['value'])}")
    out += ["}", ""]
    return "\n".join(out)


def planned_files() -> dict[Path, str]:
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    colors = resolve_colors(data["color"]["tokens"])
    files: dict[Path, str] = {
        COLORS_DIR / "Contents.json": json.dumps({"info": XCODE_INFO}, indent=2) + "\n",
    }
    for name, value, _ in colors:
        files[COLORS_DIR / f"{name}.colorset" / "Contents.json"] = colorset(value["light"], value["dark"])
        if name == "accent":
            files[ACCENT_DIR / "Contents.json"] = colorset(value["light"], value["dark"])
    files[SWIFT_OUT] = swift_source(colors, data["spacing"]["tokens"], data["radius"]["tokens"])
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report whether generated files are up to date")
    args = parser.parse_args()

    files = planned_files()
    expected_sets = {p.parent.name for p in files if p.parent.parent == COLORS_DIR}
    existing_sets = {p.name for p in COLORS_DIR.glob("*.colorset")} if COLORS_DIR.exists() else set()
    stale_sets = existing_sets - expected_sets

    if args.check:
        outdated = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for path in outdated:
            print(f"out of date: {path.relative_to(ROOT)}")
        for name in sorted(stale_sets):
            print(f"no longer a token: {(COLORS_DIR / name).relative_to(ROOT)}")
        return 1 if outdated or stale_sets else 0

    for name in stale_sets:
        shutil.rmtree(COLORS_DIR / name)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(expected_sets)} color sets, AccentColor and {SWIFT_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
